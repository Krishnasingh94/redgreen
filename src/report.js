// Builds a PR description / bug report from REAL run artifacts only.
export function buildReport({ report, run, repro, fix, baseline }) {
  const ev = report.events.filter((e) => (repro.evidence_ids || []).includes(e.id));
  const verdictLine = fix ? '✅ **Verified**: reproduction test failed before the patch and passes after it; existing tests still pass.' : '⚠️ **Reproduced, not fixed**: a failing test reproduces the bug, but no proposed patch passed verification.';
  return `## Fix: ${repro.test_name}

${verdictLine}

**Bug report (user):** ${report.description}

### Hypothesis (model, Gemma — \`${repro.model}\`)
${repro.hypothesis}

- Expected: ${repro.expected}
- Actual: ${repro.actual}

### Evidence cited (captured, redacted)
${ev.length ? ev.map((e) => `- \`${e.id}\` @${e.t_ms}ms **${e.type}** ${e.name ? `\`${e.name}(${JSON.stringify(e.args).slice(1, -1)})\`` : ''} ${e.message ? '— ' + e.message : ''}${e.status ? ` — HTTP ${e.status}` : ''}`).join('\n') : '_none cited_'}

### Reproduction test (\`test/repro.test.js\`)
\`\`\`js
${repro.test_code.trim()}
\`\`\`

### Before patch
- Existing suite: ${baseline.pass} passed, ${baseline.fail} failed (did not catch the bug)
- Reproduction test: **FAILED** (exit ${repro.result.exitCode}, assertion error) ❌
${fix ? `
### Patch
Root cause: ${fix.root_cause}
${fix.change ? `\nChange (as stated by the model): ${fix.change}\n` : ''}
\`\`\`diff
${fix.diff}
\`\`\`

### After patch
- Reproduction test: **${fix.results[0].passed ? 'PASSED' : 'FAILED'}** (${fix.results[0].pass} passed, ${fix.results[0].fail} failed)
- Existing suite: **${fix.results[1].passed ? 'PASSED' : 'FAILED'}** (${fix.results[1].pass} passed, ${fix.results[1].fail} failed)
` : ''}
---
_Generated by RedGreen run \`${run.id}\`. Model: \`${repro.model}\`. Tests executed in a throwaway sandbox (Node ${run.sandbox.node}, permission model: ${run.sandbox.permissionModel}, timeout ${run.sandbox.timeoutMs}ms). AI-written code was not trusted until the tests above actually ran._
`;
}
